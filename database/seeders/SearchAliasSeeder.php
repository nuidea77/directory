    public function run(): void
    {
        $categories = Category::whereIn('slug', array_keys(self::ALIASES))->get()->keyBy('slug');

        foreach (self::ALIASES as $slug => $terms) {
            $category = $categories->get($slug);

            if ($category === null) {
                continue;
            }

            foreach ($terms as $term) {
                SearchAlias::updateOrCreate(
                    ['category_id' => $category->id, 'term_key' => SearchText::fold($term)],
                    ['term' => $term],
                );
            }
        }
